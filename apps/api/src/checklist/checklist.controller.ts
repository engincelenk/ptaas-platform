import {
  Controller, Get, Patch, Delete, Param, Body, Res, UseGuards, HttpCode, HttpStatus,
} from '@nestjs/common';
import { Response } from 'express';
import PDFDocument from 'pdfkit';
import { ApiTags, ApiBearerAuth, ApiOperation } from '@nestjs/swagger';
import { ChecklistService, UpdateItemDto } from './checklist.service';
import { CHECKLIST } from './checklist.constants';
import { JwtAuthGuard } from '../auth/guards/jwt-auth.guard';
import { CurrentUser } from '../auth/decorators/current-user.decorator';
import type { JwtPayload } from '../auth/strategies/jwt.strategy';

@ApiTags('checklist')
@ApiBearerAuth()
@UseGuards(JwtAuthGuard)
@Controller('projects/:projectId/checklist')
export class ChecklistController {
  constructor(private readonly svc: ChecklistService) {}

  @Get()
  @ApiOperation({ summary: 'Get full OWASP checklist with completion state' })
  get(@Param('projectId') projectId: string, @CurrentUser() user: JwtPayload) {
    return this.svc.getChecklist(projectId, user.orgId);
  }

  @Patch(':itemKey')
  @ApiOperation({ summary: 'Check or uncheck a checklist item' })
  update(
    @Param('projectId') projectId: string,
    @Param('itemKey') itemKey: string,
    @Body() dto: UpdateItemDto,
    @CurrentUser() user: JwtPayload,
  ) {
    return this.svc.updateItem(projectId, user.orgId, itemKey, user.sub, dto);
  }

  @Delete('reset')
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiOperation({ summary: 'Reset all checklist items for this project' })
  reset(@Param('projectId') projectId: string, @CurrentUser() user: JwtPayload) {
    return this.svc.resetChecklist(projectId, user.orgId);
  }

  @Get('export.pdf')
  @ApiOperation({ summary: 'Export checklist as PDF' })
  async exportPdf(
    @Param('projectId') projectId: string,
    @CurrentUser() user: JwtPayload,
    @Res() res: Response,
  ) {
    const data = await this.svc.getChecklistSummary(projectId, user.orgId);
    const doc = new PDFDocument({ size: 'A4', margin: 50 });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="checklist-${projectId}.pdf"`);
    doc.pipe(res);

    // Header
    doc.rect(0, 0, doc.page.width, 80).fill('#1e1b4b');
    doc.fillColor('#ffffff').fontSize(18).font('Helvetica-Bold')
       .text('Pentest Methodology Checklist', 50, 28);
    doc.fontSize(10).font('Helvetica')
       .text(`${data.project?.name ?? projectId}  ·  ${data.project?.organization?.name ?? ''}`, 50, 52);

    doc.fillColor('#000000').moveDown(4);

    // Progress summary
    const { progress } = data;
    doc.fontSize(12).font('Helvetica-Bold').text('Progress', 50, 100);
    doc.fontSize(10).font('Helvetica')
       .text(`${progress.checked} / ${progress.total} items completed (${progress.pct}%)`, 50, 116);

    // Progress bar
    doc.rect(50, 130, 495, 8).fillOpacity(0.15).fill('#6366f1');
    doc.rect(50, 130, 495 * (progress.pct / 100), 8).fillOpacity(1).fill('#6366f1');
    doc.fillOpacity(1);

    let y = 160;
    const PAGE_H = doc.page.height - 50;

    for (const cat of data.categories) {
      if (y > PAGE_H - 60) { doc.addPage(); y = 50; }

      // Category header
      doc.rect(50, y, 495, 22).fill('#eef2ff');
      doc.fillColor('#3730a3').fontSize(10).font('Helvetica-Bold')
         .text(`${cat.icon}  ${cat.label}`, 58, y + 6);
      doc.fillColor('#000000');
      y += 28;

      for (const item of cat.items) {
        if (y > PAGE_H - 20) { doc.addPage(); y = 50; }

        // Checkbox
        if (item.checked) {
          doc.rect(50, y + 1, 11, 11).fill('#6366f1');
          doc.fillColor('#ffffff').fontSize(8).text('✓', 52, y + 2);
          doc.fillColor('#000000');
        } else {
          doc.rect(50, y + 1, 11, 11).stroke('#9ca3af');
        }

        doc.fontSize(9).font(item.checked ? 'Helvetica' : 'Helvetica')
           .fillColor(item.checked ? '#6b7280' : '#111827')
           .text(item.label, 70, y + 2, { width: 380 });

        if (item.ref) {
          doc.fontSize(7).fillColor('#9ca3af').text(item.ref, 455, y + 3, { width: 90, align: 'right' });
        }

        if (item.note) {
          y += 14;
          doc.fontSize(7).fillColor('#4b5563').font('Helvetica-Oblique')
             .text(`  Note: ${item.note}`, 70, y, { width: 420 });
        }

        doc.fillColor('#000000');
        y += 16;
      }
      y += 8;
    }

    // Footer
    doc.fontSize(7).fillColor('#9ca3af')
       .text(
         `Generated by PTaaS Platform · ${new Date().toLocaleDateString('en-GB')}`,
         50,
         doc.page.height - 30,
         { align: 'center', width: 495 },
       );

    doc.end();
  }
}
